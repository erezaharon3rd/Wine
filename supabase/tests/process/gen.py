"""Builds process_test.sql: end-to-end process tests that run on the real database
inside one DO block and roll everything back at the end (nothing is saved, no notifications remain).
The report comes back as the error message of the final RAISE, which is what forces the rollback."""
import sys
L = []
def out(s): L.append(s)
def AS(u): return f"perform pg_temp.u({u});"
SYS = "perform pg_temp.u(null);"
def esc(s): return s.replace("'", "''")
def line(name, cond, detail="err"):
    out(f"  rep := rep || pg_temp.r('{esc(name)}', ({cond}), ({detail})::text);")
def H(title): out(f"  rep := rep || E'\\n' || '{esc(title)}' || E'\\n';")
def ACT(u, stmt, name, ok=True):
    """run stmt as user u; ok=True expects success, ok=False expects it to be blocked"""
    out(f"  {AS(u)}")
    out(f"  begin {stmt}; okv := true; err := null; exception when others then okv := false; err := sqlerrm; end;")
    out(f"  {SYS}")
    line(name, "okv" if ok else "not okv", "err" if ok else "'לא נחסם'")
def SEE(u, query, var):
    out(f"  {AS(u)}")
    out(f"  {query} into {var};")
    out(f"  {SYS}")
def S(stmt): out(f"  {stmt};")
def C(name, cond, detail="null"): line(name, cond, detail)

