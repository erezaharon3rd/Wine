-- =====================================================================
--  פונקציות עזר להרשאות
-- =====================================================================
create or replace function my_role() returns app_role
language sql stable security definer set search_path = public as $$
  select role from profiles where id = auth.uid() and status = 'active'
$$;

create or replace function my_org() returns uuid
language sql stable security definer set search_path = public as $$
  select org_id from profiles where id = auth.uid() and status = 'active'
$$;

create or replace function my_artist() returns uuid
language sql stable security definer set search_path = public as $$
  select a.id from artists a join profiles p on p.id = a.user_id
  where p.id = auth.uid() and p.status = 'active'
$$;

create or replace function is_admin() returns boolean
language sql stable security definer set search_path = public as $$
  select coalesce(my_role() = 'admin', false)
$$;

create or replace function can_see_deal(d bigint) returns boolean
language sql stable security definer set search_path = public as $$
  select exists (
    select 1 from deals x
    left join print_orders o on o.deal_id = x.id
    where x.id = d and (
         is_admin()
      or (my_role() = 'winery'  and x.winery_id  = my_org())
      or (my_role() = 'gallery' and x.gallery_id = my_org())
      or (my_role() = 'artist'  and x.artist_id  = my_artist())
      or (my_role() = 'curator')
      or (my_role() = 'printer' and o.printer_id = my_org())
    )
  )
$$;

-- פרופיל נוצר אוטומטית לכל משתמש חדש
create or replace function handle_new_user() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  insert into profiles (id, email, phone) values (new.id, new.email, new.phone)
  on conflict (id) do nothing;
  return new;
end $$;
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users
  for each row execute function handle_new_user();

-- משתמש רגיל לא יכול לשנות לעצמו תפקיד, ארגון או סטטוס
create or replace function guard_profile() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if not is_admin() and auth.uid() is not null and coalesce(current_setting('app.bypass', true),'') <> '1' and
     (new.role is distinct from old.role or new.org_id is distinct from old.org_id
      or new.status is distinct from old.status) then
    raise exception 'רק מנהל המערכת יכול לשנות תפקיד, ארגון או סטטוס';
  end if;
  return new;
end $$;
drop trigger if exists profiles_guard on profiles;
create trigger profiles_guard before update on profiles
  for each row execute function guard_profile();

-- =====================================================================
--  תמחור ומעבר שלבים בעסקה (רק דרך פונקציות, לא עדכון ישיר)
-- =====================================================================
create or replace function deal_price(d deals) returns numeric
language sql stable security definer set search_path = public as $$
  select round(
    round(a.floor_price
      * case d.license_type when 'series' then 2.2 else 1 end
      * case d.qty_tier when 'b' then 1.5 when 'c' then 2 else 1 end
      * case when d.exclusive then 1.6 else 1 end / 50) * 50
    * (1 + d.adj_pct / 100.0) / 50) * 50
  from artists a where a.id = d.artist_id
$$;

create or replace function notify_deal(d bigint, msg text, roles app_role[]) returns void
language plpgsql security definer set search_path = public as $$
declare x deals;
begin
  select * into x from deals where id = d;
  insert into notifications (user_id, deal_id, body)
  select p.id, d, msg from profiles p
  where p.status = 'active' and p.role = any(roles) and (
       (p.role = 'winery'  and p.org_id = x.winery_id)
    or (p.role = 'gallery' and p.org_id = x.gallery_id)
    or (p.role = 'artist'  and p.id = (select user_id from artists where id = x.artist_id))
    or (p.role = 'admin'));
end $$;

-- יקב שולח בקשה
create or replace function request_license(
  p_work bigint, p_wine bigint, p_design text, p_label text,
  p_type text, p_qty text, p_exclusive boolean) returns bigint
language plpgsql security definer set search_path = public as $$
declare w works; a artists; new_id bigint;
begin
  if coalesce(my_role()::text, '') <> 'winery' then raise exception 'רק יקב יכול לשלוח בקשה'; end if;
  select * into w from works where id = p_work and status = 'live' and available;
  if not found then raise exception 'היצירה אינה זמינה'; end if;
  select * into a from artists where id = w.artist_id;
  insert into deals (winery_id, gallery_id, artist_id, work_id, wine_id, design_code,
                     wine_label, license_type, qty_tier, exclusive, created_by)
  values (my_org(), a.gallery_id, a.id, w.id, p_wine, p_design, p_label,
          p_type, p_qty, coalesce(p_exclusive,false), auth.uid())
  returning id into new_id;
  perform notify_deal(new_id, 'בקשת רישיון חדשה', array['gallery','admin']::app_role[]);
  insert into audit_log(action, entity, entity_id) values ('request','deal',new_id::text);
  return new_id;
end $$;

-- כל שאר השלבים
create or replace function advance_deal(p_deal bigint, p_action text,
                                        p_adj int default 0, p_note text default null)
returns deal_status
language plpgsql security definer set search_path = public as $$
declare x deals; r app_role := my_role(); s settings; c numeric;
begin
  select * into x from deals where id = p_deal for update;
  if not found or not can_see_deal(p_deal) then raise exception 'אין גישה לעסקה'; end if;
  select * into s from settings where id = 1;

  if p_action = 'price' and x.status = 'sent' and r in ('gallery','admin') then
    c := s.comm_pct;
    x.adj_pct := greatest(-15, least(15, coalesce(p_adj,0)));
    update deals set adj_pct = x.adj_pct, note = p_note, comm_pct = c,
      price_net = deal_price(x), status = 'priced', updated_at = now() where id = p_deal;
    perform notify_deal(p_deal, 'הגלריה תמחרה. נדרשת הסכמת האמן', array['artist']::app_role[]);

  elsif p_action = 'approve' and x.status = 'priced' and (r = 'admin' or (r = 'artist' and x.artist_id = my_artist())) then
    update deals set status = 'sign', updated_at = now() where id = p_deal;
    insert into contracts (deal_id, terms) values (p_deal, jsonb_build_object(
      'license_type', x.license_type, 'qty_tier', x.qty_tier, 'exclusive', x.exclusive,
      'price_net', x.price_net, 'vat_pct', s.vat_pct,
      'restrict', (select restrict_text from artists where id = x.artist_id)))
    on conflict (deal_id) do nothing;
    perform notify_deal(p_deal, 'החוזה מוכן לחתימה', array['winery']::app_role[]);

  elsif p_action = 'sign' and x.status = 'sign' and r = 'winery' and x.winery_id = my_org() then
    update deals set status = 'pay', signed_at = now(), updated_at = now() where id = p_deal;
    update contracts set signed_by = auth.uid(), signed_at = now() where deal_id = p_deal;
    insert into invoices (deal_id, net, vat, total)
    values (p_deal, x.price_net, round(x.price_net * s.vat_pct / 100, 2),
            round(x.price_net * (1 + s.vat_pct / 100), 2))
    on conflict (deal_id) do nothing;
    perform notify_deal(p_deal, 'החוזה נחתם. ממתין לתשלום', array['gallery']::app_role[]);

  elsif p_action = 'paid' and x.status = 'pay' and r in ('gallery','admin') then
    p_note := nullif(p_note,'');
    update deals set status = 'active', paid_at = current_date,
      ends_at = current_date + interval '1 year', updated_at = now() where id = p_deal;
    update invoices set confirmed_by = auth.uid(), confirmed_at = now(),
      number = coalesce(nullif(p_note,''), number) where deal_id = p_deal;
    perform notify_deal(p_deal, 'הרישיון פעיל', array['winery','artist']::app_role[]);

  elsif p_action = 'change' and x.status = 'priced' and (r = 'admin' or (r = 'artist' and x.artist_id = my_artist())) then
    update deals set status = 'sent', updated_at = now() where id = p_deal;
    perform notify_deal(p_deal, 'האמן ביקש שינוי. הבקשה חזרה לתמחור', array['gallery']::app_role[]);

  elsif p_action = 'reject' and x.status in ('sent','priced')
        and (r in ('gallery','admin') or (r = 'artist' and x.artist_id = my_artist())) then
    update deals set status = 'rejected', note = p_note, updated_at = now() where id = p_deal;
    perform notify_deal(p_deal, 'הבקשה נדחתה', array['winery']::app_role[]);

  elsif p_action = 'order' and x.status = 'active' and (r = 'admin' or (r = 'winery' and x.winery_id = my_org())) then
    insert into print_orders (deal_id, printer_id, due)
    values (p_deal, (select id from organizations where kind = 'printer' and active order by created_at limit 1),
            current_date + 21)
    on conflict (deal_id) do nothing;

  elsif p_action = 'cancel' and x.status in ('sent','priced','sign')
        and (r = 'admin' or (r = 'winery' and x.winery_id = my_org())) then
    update deals set status = 'cancelled', note = p_note, updated_at = now() where id = p_deal;

  else
    raise exception 'הפעולה % אינה אפשרית בשלב הזה', p_action;
  end if;

  insert into audit_log(action, entity, entity_id, data)
  values (p_action, 'deal', p_deal::text, jsonb_build_object('adj', p_adj, 'note', p_note));
  select status into x.status from deals where id = p_deal;
  return x.status;
end $$;

