create extension if not exists pgcrypto;

-- ---------- סוגים ----------
do $$ begin
  create type app_role   as enum ('winery','artist','gallery','curator','printer','admin');
exception when duplicate_object then null; end $$;
do $$ begin
  create type deal_status as enum ('sent','priced','sign','pay','active','rejected','cancelled');
exception when duplicate_object then null; end $$;
do $$ begin
  create type work_status as enum ('pending','review','live','paused','rejected');
exception when duplicate_object then null; end $$;

-- ---------- 1. הגדרות מערכת ----------
create table if not exists settings (
  id          int primary key default 1 check (id = 1),
  vat_pct     numeric not null default 18,
  comm_min    numeric not null default 15,
  comm_max    numeric not null default 20,
  artist_share numeric not null default 50,
  render_quota int not null default 6,
  updated_at  timestamptz not null default now()
);
alter table settings add column if not exists comm_pct numeric not null default 15;
insert into settings (id) values (1) on conflict do nothing;

-- ---------- 2. ארגונים (יקב, גלריה, בית דפוס, הפלטפורמה) ----------
create table if not exists organizations (
  id         uuid primary key default gen_random_uuid(),
  kind       app_role not null check (kind in ('winery','gallery','printer','curator','admin')),
  name       text not null,
  city       text,
  site       text,
  phone      text,
  comm_pct   numeric check (comm_pct between 0 and 40),   -- עמלת גלריה
  active     boolean not null default true,
  created_at timestamptz not null default now()
);

-- ---------- 3. משתמשים ----------
create table if not exists profiles (
  id         uuid primary key references auth.users(id) on delete cascade,
  email      text,
  phone      text,
  full_name  text,
  role       app_role,                 -- נקבע על ידי מנהל המערכת
  org_id     uuid references organizations(id),
  status     text not null default 'pending' check (status in ('pending','active','blocked')),
  seen_intro text[] not null default '{}',
  created_at timestamptz not null default now()
);

-- ---------- 4. אמנים ----------
create table if not exists artists (
  id         uuid primary key default gen_random_uuid(),
  user_id    uuid unique references profiles(id) on delete set null,
  gallery_id uuid not null references organizations(id),
  name       text not null,
  bio        text,
  instagram  text,
  floor_price numeric not null default 3500,   -- מחיר רצפה לרישיון בסיסי, לפני מע״מ
  restrict_text text,                            -- שימושים שאינם מותרים
  restrict_tags text[] not null default '{}',
  created_at timestamptz not null default now()
);

alter table artists add column if not exists country text not null default 'ישראל';

-- ---------- 5. יצירות ----------
create table if not exists works (
  id         bigint generated by default as identity primary key,
  artist_id  uuid not null references artists(id) on delete cascade,
  title      text not null,
  year       int,
  size       text,
  tag        text,
  tone       text,
  status     work_status not null default 'pending',
  available  boolean not null default true,
  pick_rank  int,                 -- סדר הבחירה של האוצרות
  no_crop    jsonb not null default '{}',   -- אזורים שאסור לחתוך
  image_path text,                -- נתיב בתוך דלי works
  review_note text,
  created_at timestamptz not null default now()
