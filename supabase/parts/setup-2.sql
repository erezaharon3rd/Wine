create or replace function org_slug() returns trigger
language plpgsql as $$
begin
  if new.slug is null and new.kind = 'winery' then
    new.slug := 'w' || substr(replace(new.id::text, '-', ''), 1, 8);
  end if;
  return new;
end $$;
