-- לקוח שנכנס מהקישור של יקב
create or replace function join_as_customer(p_slug text) returns boolean
language plpgsql security definer set search_path = public as $$
declare w uuid;
begin
  select id into w from organizations where slug = p_slug and kind = 'winery' and active;
  if w is null then return false; end if;
  perform set_config('app.bypass', '1', true);
  update profiles set role = 'customer', status = 'active', org_id = w
  where id = auth.uid() and role is null and status = 'pending';
  return found;
end $$;
grant execute on function join_as_customer(text) to authenticated;

create or replace function notify_users(p_org uuid, p_role text, p_user uuid, msg text) returns void
language sql security definer set search_path = public as $$
  insert into notifications (user_id, body)
  select id, msg from profiles
  where id = p_user   -- הודעה אישית מגיעה גם למי שעוד לא פעיל (למשל בקשה שנדחתה)
     or (status = 'active' and p_org is not null and org_id = p_org and role::text = p_role);
$$;
revoke execute on function notify_users(uuid,text,uuid,text) from public, anon, authenticated;

create or replace function corder_new() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  new.log := jsonb_build_array(jsonb_build_object('t','הלקוח שלח את ההזמנה','at',now()));
  perform notify_users(new.winery_id, 'winery', null, 'הזמנת לקוח חדשה');
  return new;
end $$;
drop trigger if exists corder_new_t on customer_orders;
create trigger corder_new_t before insert on customer_orders
  for each row execute function corder_new();

create or replace function corder_action(p_id bigint, p_action text, p_design jsonb default null,
                                         p_note text default null, p_total numeric default null)
returns text
language plpgsql security definer set search_path = public as $$
declare o customer_orders; r text := my_role()::text; win boolean; cus boolean; msg text;
begin
  select * into o from customer_orders where id = p_id for update;
  if not found then raise exception 'ההזמנה לא נמצאה'; end if;
  win := r = 'admin' or (r = 'winery' and o.winery_id = my_org());
  cus := o.customer_id = auth.uid();

  if p_action = 'wsave' and win and o.status = 'sent' then
    update customer_orders set winery_design = p_design, total = coalesce(p_total, total) where id = p_id;
    return o.status;
  elsif p_action = 'wundo' and win and o.status = 'sent' then
    update customer_orders set winery_design = null where id = p_id; msg := 'היקב ביטל את ההתאמות';
  elsif p_action = 'wsend' and win and o.status = 'sent' and o.winery_design is not null then
    update customer_orders set status = 'review', winery_note = p_note where id = p_id;
    msg := 'היקב הציע התאמות לאישורך';
    perform notify_users(null, null, o.customer_id, msg);
  elsif p_action = 'wok' and win and o.status = 'sent' then
    update customer_orders set status = 'approved', winery_design = null where id = p_id;
    msg := 'היקב אישר את ההזמנה';
    perform notify_users(null, null, o.customer_id, msg);
  elsif p_action = 'cok' and cus and o.status = 'review' then
    update customer_orders set status = 'approved' where id = p_id;
    msg := 'הלקוח אישר את ההתאמות';
    perform notify_users(o.winery_id, 'winery', null, msg);
  elsif p_action = 'cchange' and cus and o.status = 'review' then
    update customer_orders set status = 'sent' where id = p_id;
    msg := 'הלקוח ביקש שינוי: ' || coalesce(p_note, '');
    perform notify_users(o.winery_id, 'winery', null, msg);
  elsif p_action = 'wpaid' and win and o.status = 'approved' and o.paid_at is null then
    update customer_orders set paid_at = now() where id = p_id;
    msg := 'היקב סימן שהתשלום התקבל';
  elsif p_action = 'wprint' and win and o.status = 'approved' and o.paid_at is not null then
    update customer_orders set status = 'print' where id = p_id;
    msg := 'ההזמנה עברה לדפוס';
    perform notify_users(null, null, o.customer_id, msg);
  elsif p_action = 'done' and (win or r = 'printer') and o.status = 'print' then
    update customer_orders set status = 'done' where id = p_id;
    msg := 'הבקבוקים מוכנים';
    perform notify_users(null, null, o.customer_id, msg);
  elsif p_action = 'cancel' and (win or cus) and o.status in ('sent','review','label') then
    update customer_orders set status = 'cancel' where id = p_id; msg := 'ההזמנה בוטלה';
  else
    raise exception 'הפעולה אינה אפשרית בשלב הזה';
  end if;
  update customer_orders set log = log || jsonb_build_array(jsonb_build_object('t', msg, 'at', now()))
  where id = p_id;
  select status into o.status from customer_orders where id = p_id;
  return o.status;
end $$;
grant execute on function corder_action(bigint,text,jsonb,text,numeric) to authenticated;

-- הודעות במערכת: גם בלי מייל, הפעמון מציג אותן
create or replace function notify_deal(d bigint, msg text, roles app_role[]) returns void
language plpgsql security definer set search_path = public as $$
declare x deals;
begin
  select * into x from deals where id = d;
  insert into notifications (user_id, deal_id, body)
  select p.id, d, msg from profiles p
  where p.status = 'active' and p.role = any(roles) and (
       (p.role = 'winery'  and p.org_id = x.winery_id)
    or (p.role = 'gallery' and p.org_id = x.gallery_id)
    or (p.role = 'artist'  and p.id = (select user_id from artists where id = x.artist_id))
    or (p.role = 'admin'));
end $$;

