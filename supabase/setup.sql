-- ---------- 6. יינות ----------
create table if not exists wines (
  id         bigint generated by default as identity primary key,
  winery_id  uuid not null references organizations(id) on delete cascade,
  name       text not null,
  vintage    int,
  type       text not null check (type in ('red','white','rose','sparkling','dessert','other')),
  bottles    int,
  created_at timestamptz not null default now()
