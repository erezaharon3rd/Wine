-- הגדרות: כולם קוראים, רק מנהל משנה
create policy settings_read  on settings for select to authenticated using (true);
create policy settings_admin on settings for update to authenticated using (is_admin());

-- ארגונים: כל משתמש פעיל רואה שמות; מנהל מנהל; גלריה מעדכנת את עצמה
create policy org_read   on organizations for select to authenticated using (my_role() is not null);
create policy org_admin  on organizations for all    to authenticated using (is_admin()) with check (is_admin());
create policy org_self   on organizations for update to authenticated
  using (id = my_org() and my_role() in ('gallery','winery','printer')) with check (id = my_org());

-- משתמשים: כל אחד רואה את עצמו ואת אנשי הארגון שלו; מנהל רואה הכל
create policy prof_self  on profiles for select to authenticated
  using (id = auth.uid() or is_admin()
         or (org_id is not null and org_id = my_org() and coalesce(my_role()::text,'') <> 'customer' and coalesce(role::text,'') <> 'customer'));
create policy prof_upd   on profiles for update to authenticated
  using (id = auth.uid() or is_admin()) with check (id = auth.uid() or is_admin());

-- אמנים: פרופיל ציבורי לכל משתמש פעיל; האמן מעדכן את עצמו; הגלריה מנהלת את האמנים שלה
create policy art_read   on artists for select to authenticated using (my_role() is not null);
create policy art_self   on artists for update to authenticated
  using (id = my_artist()) with check (id = my_artist());
create policy art_gal    on artists for all to authenticated
  using (is_admin() or (my_role() = 'gallery' and gallery_id = my_org()))
  with check (is_admin() or (my_role() = 'gallery' and gallery_id = my_org()));

-- יצירות: יקב רואה רק יצירות שאושרו; אמן, גלריה, אוצר ומנהל רואים לפי תחום
create policy work_read  on works for select to authenticated using (
     (status = 'live' and my_role() is not null)
  or artist_id = my_artist()
  or my_role() in ('curator','admin')
  or (my_role() = 'gallery' and artist_id in (select id from artists where gallery_id = my_org())));
create policy work_ins   on works for insert to authenticated with check (
     artist_id = my_artist() or is_admin()
  or (my_role() = 'gallery' and artist_id in (select id from artists where gallery_id = my_org())));
create policy work_upd   on works for update to authenticated using (
     artist_id = my_artist() or my_role() in ('curator','admin')
  or (my_role() = 'gallery' and artist_id in (select id from artists where gallery_id = my_org())));
create policy work_del   on works for delete to authenticated using (is_admin()
  or (artist_id = my_artist() and status in ('pending','rejected')));

-- אמן לא יכול לאשר לעצמו יצירה. הגלריה מעבירה לבדיקה, האוצרות מפרסמים
create or replace function guard_work() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if coalesce(my_role()::text,'') not in ('curator','admin') and auth.uid() is not null then
    if tg_op = 'INSERT' then new.status := 'pending'; new.pick_rank := null;
    elsif new.status is distinct from old.status and my_role() = 'gallery'
          and old.status = 'pending' and new.status in ('review','rejected') then
      null;
    elsif new.status is distinct from old.status and new.status in ('live','review','rejected') then
      raise exception 'רק האוצרות מאשרים יצירות';
    elsif new.pick_rank is distinct from old.pick_rank then
      new.pick_rank := old.pick_rank;
    end if;
  end if;
  return new;
